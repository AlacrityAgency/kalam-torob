def translate_colloquial(raw_text: str) -> ColloquialTranslation:
    """
    بررسی و ترجمه اصطلاح عامیانه به مشخصات ساختاریافته کاتالوگ ترب.
    اگر هیچ اصطلاحی منطبق نشد، آبجکت خالی با is_colloquial=False برمی‌گرداند.
    """
    text = clean_conversational_text(raw_text)
    is_where = detect_where_to_buy_intent(raw_text)

    for pattern in COLLOQUIAL_PATTERNS:
        match = pattern["regex"].search(text)
        if match:
            return ColloquialTranslation(
                is_colloquial=True,
                concept_key=pattern["concept"],
                display_label=pattern["display_label"],
                target_category=pattern.get("category"),
                tokens=list(pattern["tokens"]),
                optional_tokens=list(pattern.get("optional", [])),
                implied_budget_min=pattern.get("budget_min"),
                implied_budget_max=pattern.get("budget_max"),
                friendly_note=pattern.get("note"),
                bazaar_hub_guide=pattern.get("hub"),
                where_to_buy=is_where,
            )

    return ColloquialTranslation(is_colloquial=False, where_to_buy=is_where)
