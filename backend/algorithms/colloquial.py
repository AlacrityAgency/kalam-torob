_CLEAN_REGEX = re.compile("|".join(PRONOUNS_AND_FILLERS), flags=re.IGNORECASE)


def clean_conversational_text(text: str) -> str:
    """حذف ضمایر و فیلرهای گفتگویی و علائم نگارشی از متن کاربر"""
    cleaned = _CLEAN_REGEX.sub(" ", text or "")
    # حذف علائم نگارشی چسبیده و علامت‌های سوالی
    cleaned = re.sub(r"[؟?!,،.:;«»\"'()\[\]{}]+", " ", cleaned)
    # حذف فاصله‌های متوالی
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    return cleaned


def detect_where_to_buy_intent(text: str) -> bool:
    """آیا کاربر به دنبال بورس یا محل فروش کالا است؟ («کجاها میفروشن»، «از کجا بخرم»)"""
    return bool(re.search(r"کجا|میفروشن|می‌فروشن|میفروشند|گیر\s*میاد|کجا\s*داره|از\s*کجا|بورس|راسته|مرکز\s*خرید", text or "", re.IGNORECASE))


